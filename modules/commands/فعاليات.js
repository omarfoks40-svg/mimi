async function startRound(api, threadID, session) {
  const gameKey = session.gameOrder[session.currentGameIndex];
  const game = GAMES[gameKey];

  if (session.currentRound >= session.maxRounds) {
    await endGame(api, threadID, session);
    return;
  }

  const { q, idx } = pickQuestion(gameKey, session);
  session.usedQuestions.add(idx);
  session.currentQuestion = q;
  session.currentRound++;

  const roundMsg =
    `⎔ ⋅ ───━ •﹝🌿﹞• ━─── ⋅ ⎔\n` +
    `${game.icon} ┊『 ${game.label} 』\n` +
    `┊ الجولة ${session.currentRound} / ${session.maxRounds}\n` +
    `⎔ ⋅ ───━ •﹝🌿﹞• ━─── ⋅ ⎔\n\n` +
    `❓ ${q.q}\n\n` +
    `⏰ لديك ${game.timePerRound} ثانية للإجابة!\n` +
    `✦─━── •﹝🌿﹞• ──━─✦`;

  const sent = await api.sendMessage(roundMsg, threadID);
  session.roundMsgID = sent.messageID;
  registerReply(threadID, sent.messageID, 'playing');

  if (session.roundTimer) clearTimeout(session.roundTimer);
  session.roundTimer = setTimeout(async () => {
    const cur = global.فعالياتSessions[threadID];
    if (!cur || cur.roundMsgID !== sent.messageID) return;

    await api.sendMessage(
      `⏰ انتهى الوقت!\n✨ الإجابة الصحيحة كانت: ${q.a}\n\n💡 تلميح: ${q.hint}`,
      threadID
    );
    cur.currentRound++;
    if (cur.currentRound > cur.maxRounds) {
      await endGame(api, threadID, cur);
    } else {
      cur.currentRound--;
      await startRound(api, threadID, cur);
    }
  }, game.timePerRound * 1000);
}

// ══════════════════════════════════════════════
//  انتهاء اللعبة / الانتقال للتالية
// ══════════════════════════════════════════════

async function endGame(api, threadID, session) {
  if (session.roundTimer) clearTimeout(session.roundTimer);

  const gameKey = session.gameOrder[session.currentGameIndex];
  const game = GAMES[gameKey];

  const board = buildLeaderboard(session.players);
  await api.sendMessage(
    `✦─━── •﹝🌿﹞• ──━─✦\n` +
    `${game.icon} انتهت لعبة 『 ${game.label} 』!\n` +
    `✦─━── •﹝🌿﹞• ──━─✦\n\n` +
    `🏆 النتائج الحالية:\n${board}\n` +
    `✦─━── •﹝🌿﹞• ──━─✦`,
    threadID
  );

  session.currentGameIndex++;

  if (session.currentGameIndex >= session.gameOrder.length) {
    await finalLeaderboard(api, threadID, session);
    return;
  }

  const nextGameKey = session.gameOrder[session.currentGameIndex];
  const nextGame = GAMES[nextGameKey];

  session.currentRound = 0;
  session.usedQuestions.clear();

  await api.sendMessage(
    `⎔ ⋅ ───━ •﹝🌿﹞• ━─── ⋅ ⎔\n` +
    `🎮 الانتقال التلقائي للعبة التالية...\n` +
    `${nextGame.icon} 『 ${nextGame.label} 』\n` +
    `⎔ ⋅ ───━ •﹝🌿﹞• ━─── ⋅ ⎔`,
    threadID
  );

  setTimeout(() => startRound(api, threadID, session), 3000);
}

