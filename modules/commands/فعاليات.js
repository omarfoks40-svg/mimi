function getGamesMenu() {
  const keys = Object.keys(GAMES);
  let menu = '';
  keys.forEach((key, i) => {
    const g = GAMES[key];
    menu += `${g.icon}┊⇇『 ${g.label} 』 — (${i + 1})\n`;
  });
  return menu;
}

function normalize(str) {
  return (str || '')
    .trim()
    .toLowerCase()
    .replace(/[أإآا]/g, 'ا')
    .replace(/[ةه]/g, 'ه')
    .replace(/[ىي]/g, 'ي')
    .replace(/\s+/g, ' ');
}

function isCorrect(answer, userInput) {
  return normalize(userInput).includes(normalize(answer)) ||
    normalize(answer).includes(normalize(userInput));
}

function pickQuestion(gameKey, session) {
  const pool = GAMES[gameKey].questions;
  const used = session.usedQuestions;
  const available = pool.filter((_, i) => !used.has(i));
  if (available.length === 0) {
    used.clear();
    return { q: pool[0], idx: 0 };
  }
  const idx = pool.indexOf(available[Math.floor(Math.random() * available.length)]);
  return { q: pool[idx], idx };
}

function buildLeaderboard(players) {
  const sorted = [...players.values()].sort((a, b) => b.score - a.score);
  if (sorted.length === 0) return '⟣ لا يوجد نقاط ⟢';

  const medals = ['🥇', '🥈', '🥉'];
  let board = '';
  sorted.forEach((p, i) => {
    const medal = medals[i] || `${i + 1}.`;
    board += `${medal} ${p.name} — ${p.score} نقطة\n`;
  });
  return board;
}

function clearSession(threadID) {
  const s = global.فعالياتSessions[threadID];
  if (!s) return;
  if (s.roundTimer) clearTimeout(s.roundTimer);
  if (s.regTimer) clearTimeout(s.regTimer);
  delete global.فعالياتSessions[threadID];
  global.client.handleReply = (global.client.handleReply || []).filter(
    r => r.threadID !== threadID || r.name !== 'فعاليات'
  );
}

function registerReply(threadID, msgID, phase, extra = {}) {
  global.client.handleReply = (global.client.handleReply || []).filter(
    r => !(r.name === 'فعاليات' && r.threadID === threadID)
  );
  global.client.handleReply.push({
    name: 'فعاليات',
    messageID: msgID,
    threadID,
    phase,
    ...extra,
  });
}

